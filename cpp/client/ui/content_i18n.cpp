const char* lookup(const Pair* table, std::size_t n, const std::string& id,
                   const char* fallback) {
    if (!zh()) return fallback;
    for (std::size_t i = 0; i < n; ++i) {
        if (id == table[i].id) return table[i].zh;
    }
    return fallback;
}
